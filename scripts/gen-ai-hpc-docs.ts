/**
 * Generates the data-derived AI/HPC demo docs from the topology, evidence generator and scenarios,
 * so the docs cannot drift from what the seed actually creates.
 * Usage: npx tsx scripts/gen-ai-hpc-docs.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildTopology, DEMO, FABRIC_DESIGN, type DeviceSpec } from "../src/lib/demo/ai-hpc/topology";
import { cablesByFabric, validateTopology } from "../src/lib/demo/ai-hpc/validate";
import { SNAPSHOTS, SNAPSHOT_META, STALE_DEVICE, PARSER_ERROR_DEVICE, DUP_HOSTS, evidenceFiles, faultExpectations } from "../src/lib/demo/ai-hpc/evidence";
import { DEMO_SCENARIOS } from "../src/lib/demo/ai-hpc/scenarios";

const t = buildTopology();
const OUT = join(process.cwd(), "docs", "demo");
const HEADER = `> **DEMO / SYNTHETIC DATA.** ${DEMO.organization}, ${DEMO.site} and every device, user, address and IP below are fictional. Generated by \`scripts/gen-ai-hpc-docs.ts\` from \`src/lib/demo/ai-hpc/*\`; do not edit by hand.\n`;
const cell = (v: unknown) => String(v ?? "\u2014").replace(/\|/g, "\\|");
const table = (head: string[], rows: unknown[][]) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");

function write(name: string, title: string, body: string) {
  writeFileSync(join(OUT, name), `# ${title}\n\n${HEADER}\n${body.trim()}\n`);
  console.log(`wrote docs/demo/${name}`);
}

function observability(d: DeviceSpec) {
  if (d.discovery.collectable && d.discovery.transmits) return "Collect + transmit";
  if (d.discovery.transmits) return "Transmits only (no collection)";
  if (d.discovery.collectable) return "Collect only";
  return "Not observable";
}

mkdirSync(OUT, { recursive: true });

const issues = validateTopology(t);
const fabricCounts = cablesByFabric(t.cables);
const byFabric = Object.fromEntries(Object.keys(fabricCounts).map((f) => [f, t.cables.filter((c) => c.fabric === f)]));

write(
  "AI_HPC_DEMO_RACK_LAYOUT.md",
  "AI/HPC Demo \u2014 Rack Layout",
  `${t.racks.length} racks, ${t.devices.length} devices. Topology validation: ${issues.length === 0 ? "**no issues** (RU bounds, overlaps, ports, speeds, fabric roles, no FE\u2194BE bridge)" : `**${issues.length} issue(s)**`}.

${t.racks
  .map((r) => {
    const devs = t.devices.filter((d) => d.rack === r.name).sort((a, b) => b.rackUnit - a.rackUnit);
    const used = devs.reduce((n, d) => n + d.uHeight, 0);
    return `## ${r.name} \u2014 ${r.purpose}\n\nRow ${r.row} \u00b7 ${r.heightU}U \u00b7 ${used}U used \u00b7 tag \`${r.fabricTag}\`\n\n${table(
      ["U (bottom)", "Height", "Device", "Role", "Model (fictional profile)"],
      devs.map((d) => [d.rackUnit, `${d.uHeight}U`, d.name, d.role, d.model]),
    )}`;
  })
  .join("\n\n")}`,
);

write(
  "AI_HPC_DEMO_DEVICE_INVENTORY.md",
  "AI/HPC Demo \u2014 Device Inventory",
  `${t.devices.length} devices. "Observability" is how LLDP/CDP evidence can be obtained for the device: whether RackPatch can collect its neighbor table and whether it transmits LLDP/CDP for its neighbors to see.

${table(
  ["Device", "Rack", "U", "Role", "Vendor (fictional profile)", "OS profile", "Ports", "Observability", "Note"],
  t.devices.map((d) => [d.name, d.rack, d.rackUnit, d.role, d.vendor, d.os, d.ports.length, observability(d), d.discovery.reason ?? ""]),
)}`,
);

write(
  "AI_HPC_DEMO_CABLE_MATRIX.md",
  "AI/HPC Demo \u2014 Cable Matrix",
  `${t.cables.length} planned cables. Import fixture: \`fixtures/demos/ai-hpc/pod-a-plan.csv\`.

${table(["Fabric", "Cables"], Object.entries(fabricCounts))}

## Fabric design metadata (not verified by LLDP/CDP)

${Object.entries(FABRIC_DESIGN)
  .map(([f, attrs]) => `**${f}**: ${Object.entries(attrs).map(([k, v]) => `${k} = ${v}`).join("; ")}`)
  .join("\n\n")}

${Object.entries(byFabric)
  .map(
    ([f, list]) =>
      `## ${f}\n\n${table(
        ["Cable", "A (rack / device / port)", "Z (rack / device / port)", "Type", "Speed", "Length m", "Connector", "Rail"],
        list.map((c) => [c.cableId, `${c.a.rack} / ${c.a.device} / ${c.a.port}`, `${c.z.rack} / ${c.z.device} / ${c.z.port}`, c.cableType, c.speed, c.lengthM, c.connector, c.rail]),
      )}`,
  )
  .join("\n\n")}`,
);

write(
  "AI_HPC_DEMO_SCENARIOS.md",
  "AI/HPC Demo \u2014 Scenarios",
  `${DEMO_SCENARIOS.length} guided scenarios. The same list drives the in-app **Start demo tour** button. Routes are relative to the demo project. Users sign in as \`<key>@${DEMO.emailDomain}\`.

${DEMO_SCENARIOS.map(
  (s) =>
    `## ${s.id}. ${s.title}\n\n- **Route:** \`${s.route || "(overview)"}\`\n- **Sign in as:** \`${s.as}\`\n- **Show:** ${s.show.join("; ")}\n- **Expected:** ${s.expect}${s.limitation ? `\n- **Limitation:** ${s.limitation}` : ""}`,
).join("\n\n")}`,
);

const counts = SNAPSHOTS.map((s) => {
  const files = evidenceFiles(s);
  return [s, SNAPSHOT_META[s].capture, files.length, files.filter((f) => f.importForVerification).length, SNAPSHOT_META[s].explain];
});
const neighborDevices = t.devices.filter((d) => d.discovery.collectable);
write(
  "CDP_LLDP_COVERAGE_MATRIX.md",
  "CDP/LLDP Coverage Matrix",
  `RackPatch verifies **physical cabling** from LLDP/CDP neighbor tables. It does not verify routing, BGP, ECN/PFC, RDMA performance, congestion control or firewall reachability.

## Snapshots (stored synthetic captures, not a live SSH collection)

${table(["Snapshot", "Capture time (UTC)", "Files", "Imported for verification", "Meaning"], counts)}

## Per OS profile

${table(
  ["OS profile", "Devices", "Neighbor command(s) generated", "Imported format"],
  Array.from(new Set(t.devices.map((d) => d.os))).map((os) => {
    const files = evidenceFiles("BASELINE").filter((f) => f.os === os);
    return [
      os,
      t.devices.filter((d) => d.os === os).length,
      Array.from(new Set(files.map((f) => `\`${f.command}\``))).join(", ") || "none (not collectable)",
      Array.from(new Set(files.filter((f) => f.importForVerification).map((f) => f.formatId))).join(", ") || "\u2014",
    ];
  }),
)}

## Devices without collectable neighbor evidence

${table(["Device", "Role", "Why"], t.devices.filter((d) => !d.discovery.collectable).map((d) => [d.name, d.role, d.discovery.reason ?? "Does not run LLDP/CDP or has no supported parser"]))}

${neighborDevices.length} devices produce neighbor evidence. A link side is observable when RackPatch collects that side's neighbor table and the far side transmits LLDP/CDP. Links with no observable side are classified **UNOBSERVABLE** and need a physical check; they are never marked LLDP-verified.`,
);

const sample = evidenceFiles("FAULT_INJECTED");
const pick = Array.from(new Map(sample.filter((f) => f.kind !== "INTERFACE_STATE").map((f) => [`${f.os}|${f.command}`, f])).values());
write(
  "CDP_LLDP_COMMAND_OUTPUTS.md",
  "CDP/LLDP Command Outputs (samples)",
  `One sample per OS profile and command from the FAULT_INJECTED snapshot. Every generated file starts with a \`SYNTHETIC DEMO\` header. The full set is visible per device in **Evidence \u2192 Explorer**.

${pick
  .map((f) => {
    const lines = f.text.split("\n");
    return `## ${f.device} \u2014 \`${f.command}\` (${f.os})\n\nKind: ${f.kind} \u00b7 imported: ${f.importForVerification ? `yes (${f.formatId})` : "no (reference)"}\n\n\`\`\`text\n${lines.slice(0, 40).join("\n")}${lines.length > 40 ? `\n\u2026 (${lines.length - 40} more lines)` : ""}\n\`\`\``;
  })
  .join("\n\n")}`,
);

write(
  "CDP_LLDP_FAULT_SCENARIOS.md",
  "CDP/LLDP Fault Scenarios",
  `Twelve injected faults in the FAULT_INJECTED snapshot. Stale device: \`${STALE_DEVICE}\`. Parser-error device: \`${PARSER_ERROR_DEVICE}\`. Duplicate host identity: ${DUP_HOSTS.map((d) => `\`${d}\``).join(", ")}.
Each row is asserted by \`tests/ai-hpc-demo.test.ts\` (pure engine) and \`scripts/verify-ai-hpc-demo.ts\` (database).

${faultExpectations()
  .map(
    (f) =>
      `## ${f.id}. ${f.title}\n\n${f.explain}\n\n${table(
        ["Cable", "Expected (fault)", "Expected (corrected)"],
        f.cableIds.map((c) => [c, f.expected[c], f.corrected[c]]),
      )}`,
  )
  .join("\n\n")}`,
);
